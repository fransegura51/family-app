//   · Menú y plan del día: añadir un plato · preparar la compra del menú · plan del día.
// Todo señala controles REALES de EventosScreen.tsx / EventMenu.tsx / MenuShoppingModal.tsx / EventDayPlan.tsx / InvitationDesigner.tsx (marcas data-help-id «eventos.*») y nunca ejecuta nada
