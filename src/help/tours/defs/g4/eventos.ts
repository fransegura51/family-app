// Pasos comunes: llegar a un módulo concreto desde la lista de eventos. Si la persona ya está dentro del evento (o del módulo), se omiten solos.
const abrirEvento = (siguiente: string): TourStep => ({
  id: 'evento',
  text: 'Entra en uno de tus eventos tocando su tarjeta. Si todavía no tienes ninguno, créalo antes con «+ Nuevo evento».',
  target: 'eventos.event-card',
  completeOn: [{ type: 'click', target: 'eventos.event-card' }],
  skipIf: [
    { type: 'appear', target: 'eventos.module-grid' },
    { type: 'appear', target: siguiente },
  ],
})

const abrirModulo = (id: string, texto: string, marca: string, dentro: string): TourStep => ({
  id,
  text: texto,
  target: marca,
  completeOn: [{ type: 'click', target: marca }],
  skipIf: [{ type: 'appear', target: dentro }],
})

